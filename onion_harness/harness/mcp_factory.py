"""Create MCP - the AI builds its own tool chain.

A generated tool is a self-contained Python script implementing the MCP stdio
protocol subset Onion speaks (``initialize`` / ``tools/list`` / ``tools/call``).
It lives under ``~/.onionharness/mcp/<name>/`` so it is inspectable, versioned by
the ledger, and removable.

Safety posture:

* generation is a **ledger change** like any other self-modification, so it is
  proposed, confirmed, versioned and revertible;
* the script must pass a static check (imports allow-listed, no ``eval`` of
  remote input, no network by default);
* enabling/disabling is a separate persisted flag, so a tool can be disabled
  without deleting the audit record.
"""

from __future__ import annotations

import json
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional

from onion_harness.core.mcp_contract import (  # noqa: F401
    ALLOWED_IMPORTS,
    McpError,
    validate_spec,
)

@dataclass
class McpToolSpec:
    """The contract a model supplies to create a tool."""

    name: str
    title: str
    description: str
    parameters: Dict[str, Any]
    code: str
    enabled: bool = True
    created_at: float = field(default_factory=time.time)
    version: Optional[int] = None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "name": self.name,
            "title": self.title,
            "description": self.description,
            "parameters": self.parameters,
            "enabled": self.enabled,
            "created_at": self.created_at,
            "version": self.version,
            "path": f"mcp/{self.name}/tool.py",
        }


# --- the MCP server scaffold ------------------------------------------------
SCAFFOLD = '''"""MCP tool: {title}

Generated by Onion Harness through the change ledger (v{version}).
Protocol: JSON-RPC 2.0 over stdio, implementing initialize / tools/list /
tools/call.

The generated tool code appears verbatim below; the scaffold beneath it is
standard and only wires the function into the MCP server loop.
"""

from __future__ import annotations

import json
import sys

PROTOCOL_VERSION = "2024-11-05"
TOOL_NAME = {name_repr}
TOOL_DESCRIPTION = {description_repr}
TOOL_SCHEMA = {schema_repr}


# --------------------------------------------------------------------------
# generated tool (defines handle(arguments))
# --------------------------------------------------------------------------
{body}


# --------------------------------------------------------------------------
# scaffold
# --------------------------------------------------------------------------
def _respond(msg_id, result):
    sys.stdout.write(json.dumps({{"jsonrpc": "2.0", "id": msg_id, "result": result}}) + "\\n")
    sys.stdout.flush()


def _error(msg_id, code, message):
    sys.stdout.write(
        json.dumps({{"jsonrpc": "2.0", "id": msg_id, "error": {{"code": code, "message": message}}}}) + "\\n"
    )
    sys.stdout.flush()


def main():
    for line in sys.stdin:
        line = line.strip()
        if not line:
            continue
        try:
            request = json.loads(line)
        except json.JSONDecodeError:
            continue

        method = request.get("method")
        msg_id = request.get("id")

        if method == "initialize":
            _respond(msg_id, {{
                "protocolVersion": PROTOCOL_VERSION,
                "capabilities": {{"tools": {{}}}},
                "serverInfo": {{"name": TOOL_NAME, "version": "1.0.0"}},
            }})
        elif method == "tools/list":
            _respond(msg_id, {{"tools": [{{
                "name": TOOL_NAME,
                "description": TOOL_DESCRIPTION,
                "inputSchema": TOOL_SCHEMA,
            }}]}})
        elif method == "tools/call":
            params = request.get("params") or {{}}
            arguments = params.get("arguments") or {{}}
            try:
                result = handle(arguments)
                text = result if isinstance(result, str) else json.dumps(result, ensure_ascii=False, default=str)
                _respond(msg_id, {{"content": [{{"type": "text", "text": text}}], "isError": False}})
            except Exception as exc:
                _respond(msg_id, {{
                    "content": [{{"type": "text", "text": f"{{type(exc).__name__}}: {{exc}}"}}],
                    "isError": True,
                }})
        elif msg_id is not None:
            _error(msg_id, -32601, f"Unknown method: {{method}}")


if __name__ == "__main__":
    main()
'''


def render_tool(spec: McpToolSpec) -> str:
    """Insert the model's code verbatim as module-level definitions."""
    body = spec.code.strip("\n")
    return SCAFFOLD.format(
        title=spec.title,
        version=spec.version or 1,
        name_repr=json.dumps(spec.name),
        description_repr=json.dumps(spec.description, ensure_ascii=False),
        schema_repr=json.dumps(spec.parameters, ensure_ascii=False, indent=4),
        body=body,
    )


class McpStore:
    """Filesystem store for generated MCP tools."""

    def __init__(self, root: str | Path) -> None:
        self.root = Path(root)
        (self.root / "mcp").mkdir(parents=True, exist_ok=True)
        self.index_path = self.root / "mcp" / "index.json"

    @property
    def mcp_dir(self) -> Path:
        return self.root / "mcp"

    # -- index --------------------------------------------------------------
    def load_index(self) -> List[Dict[str, Any]]:
        if not self.index_path.exists():
            return []
        try:
            raw = json.loads(self.index_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            return []
        return raw if isinstance(raw, list) else []

    def save_index(self, entries: List[Dict[str, Any]]) -> None:
        tmp = self.index_path.with_suffix(".json.tmp")
        tmp.write_text(json.dumps(entries, ensure_ascii=False, indent=2), encoding="utf-8")
        import os

        os.replace(tmp, self.index_path)

    def upsert(self, spec: McpToolSpec) -> Dict[str, Any]:
        entry = spec.to_dict()
        entries = [item for item in self.load_index() if item.get("name") != spec.name]
        entries.append(entry)
        self.save_index(entries)
        return entry

    def set_enabled(self, name: str, enabled: bool) -> bool:
        entries = self.load_index()
        found = False
        for entry in entries:
            if entry.get("name") == name:
                entry["enabled"] = enabled
                found = True
        if found:
            self.save_index(entries)
        return found

    def remove(self, name: str) -> bool:
        entries = [item for item in self.load_index() if item.get("name") != name]
        self.save_index(entries)
        target = self.mcp_dir / name
        if target.exists() and target.is_dir():
            import shutil

            shutil.rmtree(target, ignore_errors=True)
            return True
        return False

    # -- files --------------------------------------------------------------
    def tool_dir(self, name: str) -> Path:
        return self.mcp_dir / name

    def write_tool(self, spec: McpToolSpec) -> Path:
        target = self.tool_dir(spec.name)
        target.mkdir(parents=True, exist_ok=True)
        script = target / "tool.py"
        script.write_text(render_tool(spec), encoding="utf-8")
        (target / "tool.json").write_text(
            json.dumps(spec.to_dict(), ensure_ascii=False, indent=2), encoding="utf-8"
        )
        return script

    def script_exists(self, name: str) -> bool:
        return (self.tool_dir(name) / "tool.py").is_file()

    def enabled_entries(self) -> List[Dict[str, Any]]:
        return [entry for entry in self.load_index() if entry.get("enabled", True)]


